# Build font array (128 chars, 16 bytes each)
FONT = []
for c in range(128):
    if c in _CHARS:
        FONT.append(_CHARS[c])
    else:
        FONT.append([0] * 16)


def generate_header(path: str):
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// Auto-generated 8x16 bitmap font (public domain)\n')
        f.write('#ifndef FONT8X16_H\n#define FONT8X16_H\n\n')
        f.write('#include <stdint.h>\n\n')
        f.write(f'#define FONT8X16_WIDTH  8\n')
        f.write(f'#define FONT8X16_HEIGHT 16\n\n')
        f.write(f'static const uint8_t font8x16[128][{FONT_H}] = {{\n')
        for c in range(128):
            data = FONT[c]
            comment = ''
            if 32 <= c <= 126:
                comment = f' /* {chr(c)} */'
            elif c == 0:
                comment = ' /* null */'
