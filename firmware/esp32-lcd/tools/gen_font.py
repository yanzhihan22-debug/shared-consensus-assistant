"""Generate 8x16 bitmap font as C header file for ST7789 display."""

FONT_W = 8
FONT_H = 16


def _c(art: str):
    """Convert 16-line ASCII art ('.'=off, any other char=on) to 16 bytes."""
    rows = [r.rstrip('\r') for r in art.strip('\n').split('\n')]
    assert len(rows) == FONT_H, f'need {FONT_H} rows, got {len(rows)}'
    out = []
    for r in rows:
        b = 0
        for x in range(FONT_W):
            if x < len(r) and r[x] != '.':
                b |= 1 << (7 - x)
        out.append(b)
    return out


_CHARS = {}

def _def(c: str, art: str):
    _CHARS[ord(c)] = _c(art)

